"""
Нормализация распознанного текста.

Задача модуля — привести текст, полученный от движка распознавания речи,
и текст ключевых слов к ОДНОЙ общей форме, чтобы сравнение было корректным.

Пример проблемы: движок распознаёт «Часы остановились!», а в правиле
записано «часы остановились». Без нормализации это разные строки.

Что делает normalize():
    * переводит текст в нижний регистр;
    * приводит букву «ё» к «е» (самая частая причина промахов);
    * убирает пунктуацию;
    * схлопывает повторные пробелы;
    * приводит числительные к цифрам (при наличии «два часа» -> «2 часа»).

После normalize() обе строки можно сравнивать посимвольно, а разбиение
на слова (words()) даёт последовательность для нечёткого сравнения.
"""

from __future__ import annotations

import re

# Пунктуация и прочие символы, не несущие смысла
_PUNCT_RE = re.compile(r"[^\w\s]", flags=re.UNICODE)

# Повторные пробелы
_SPACES_RE = re.compile(r"\s+", flags=re.UNICODE)

# Числительные, которые чаще всего встречаются в ключевых словах.
# Приводятся к цифрам, чтобы «второй раз» и «2 раз» считались одним словом.
_NUMBERS: dict[str, str] = {
    "ноль": "0", "нуль": "0",
    "один": "1", "одна": "1", "одну": "1",
    "два": "2", "две": "2",
    "три": "3",
    "четыре": "4",
    "пять": "5",
    "шесть": "6",
    "семь": "7",
    "восемь": "8",
    "девять": "9",
    "десять": "10",
}

# Основы числительных. Нужны для падежных форм: «третьем», «втором»,
# «пятый» — у них общие только первые несколько букв.
_NUM_STEMS: dict[str, str] = {
    "перв": "1", "втор": "2", "трет": "3", "четверт": "4", "пят": "5",
    "шест": "6", "сед": "7", "восьм": "8", "девят": "9", "десят": "10",
    "дв": "2", "тр": "3", "четыр": "4",
}

# Сколько символов окончания считать допустимым: «третьем» -> «трет» + «ьем»
_MAX_ENDING = 4


def normalize(text: str) -> str:
    """Привести произвольную строку к каноническому виду.

    Возвращает строку в нижнем регистре без пунктуации и лишних пробелов.
    Пустая строка на входе даёт пустую строку на выходе.
    """
    if not text:
        return ""

    # «ё» и «е» — одна и та же буква для нашей задачи
    text = text.lower().replace("ё", "е")

    # Пунктуация -> пробел, чтобы не склеивать соседние слова
    text = _PUNCT_RE.sub(" ", text)
    text = _SPACES_RE.sub(" ", text).strip()

    return text


def _normalize_word(word: str) -> str:
    """Привести одно слово к каноническому виду (числительные -> цифры)."""
    if word in _NUMBERS:
        return _NUMBERS[word]

    # Падежная форма: ищем основу числительного в начале слова.
    for stem, digit in _NUM_STEMS.items():
        if word.startswith(stem):
            ending = word[len(stem):]
            if 0 < len(ending) <= _MAX_ENDING and ending.isalpha():
                return digit

    return word


def words(text: str) -> list[str]:
    """Разбить текст на список нормализованных слов.

    >>> words("Часы остановились!")
    ['часы', 'остановились']
    """
    normalized = normalize(text)
    if not normalized:
        return []
    return [_normalize_word(w) for w in normalized.split(" ")]


def key(text: str) -> tuple[str, ...]:
    """Текст как неизменяемый кортеж слов — удобно для хранения в кэше."""
    return tuple(words(text))


__all__ = ["normalize", "words", "key"]